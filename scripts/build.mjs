// Generates every derived file from tokens/cozy.tokens.json.
// Usage: bun run build   write the files
//        bun run check   fail if a file is out of date or a contrast pair fails
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { COZY_SPRING } from '../js/cozy-motion.js';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const tokens = JSON.parse(readFileSync(join(root, 'tokens/cozy.tokens.json'), 'utf8'));
const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));
const check = process.argv.includes('--check');
const P = '--cozy-';

if (tokens.version !== pkg.version) {
	console.error(`version mismatch: tokens/cozy.tokens.json (${tokens.version}) !== package.json (${pkg.version})`);
	process.exit(1);
}

// ---------- contrast ----------

const HEX_RE = /^#(?:[0-9a-fA-F]{6}|[0-9a-fA-F]{8})$/;
const hexToRgba = (hex) => {
	if (typeof hex !== 'string' || !HEX_RE.test(hex)) {
		throw new Error(`Invalid hex color: ${JSON.stringify(hex)}`);
	}
	const h = hex.slice(1);
	const n = (i) => parseInt(h.slice(i, i + 2), 16);
	return [n(0), n(2), n(4), h.length === 8 ? n(6) / 255 : 1];
};
const over = (fg, bg) => {
	const [r, g, b, a] = hexToRgba(fg);
	const [R, G, B] = hexToRgba(bg);
	return [r * a + R * (1 - a), g * a + G * (1 - a), b * a + B * (1 - a)];
};
const luminance = ([r, g, b]) => {
	const c = [r, g, b].map((v) => {
		const s = v / 255;
		return s <= 0.04045 ? s / 12.92 : ((s + 0.055) / 1.055) ** 2.4;
	});
	return 0.2126 * c[0] + 0.7152 * c[1] + 0.0722 * c[2];
};
const ratio = (fg, bg) => {
	const a = luminance(over(fg, bg));
	const b = luminance(hexToRgba(bg).slice(0, 3));
	return (Math.max(a, b) + 0.05) / (Math.min(a, b) + 0.05);
};

// [foreground, background, minimum ratio, kind]. 7 = AAA text, 4.5 = AA text, 3 = non-text (WCAG 1.4.11).
const pairs = [];
const add = (fgs, bgs, min, kind) => {
	for (const fg of [fgs].flat()) for (const bg of [bgs].flat()) pairs.push([fg, bg, min, kind]);
};
add(['text-primary', 'text-secondary'], ['bg-body', 'bg-surface'], 7, 'text');
add(['text-primary', 'text-secondary'], 'bg-muted', 4.5, 'text');
add('text-accent', ['bg-body', 'bg-surface'], 4.5, 'text');
add('on-accent', 'accent', 7, 'text');
add('accent-on-inverted', 'bg-inverted', 3, 'non-text');
add('focus-ring', ['bg-body', 'bg-surface'], 3, 'non-text');
add('text-on-inverted', 'bg-inverted', 7, 'text');
for (const s of ['success', 'warning', 'error', 'info']) {
	add(`text-${s}`, ['bg-body', 'bg-surface'], 4.5, 'text');
	add(`on-${s}`, s, 4.5, 'text');
	add(`on-${s}-muted`, `${s}-muted`, 4.5, 'text');
	add(s, ['bg-body', 'bg-surface'], 3, 'non-text');
	add(`${s}-on-inverted`, 'bg-inverted', 3, 'non-text');
}
add(['nav-text', 'nav-text-muted'], ['nav-bg', 'nav-active'], 4.5, 'text');
for (const p of ['sage', 'peach', 'butter', 'mist']) {
	add('text-primary', `pastel-${p}`, 7, 'text');
	add('on-pastel', `pastel-${p}-icon`, 4.5, 'text');
}
for (const c of ['green', 'orange', 'yellow', 'blue', 'teal', 'cyan', 'purple', 'pink', 'red', 'gray']) {
	add(`${c}-text`, `${c}-bg`, 4.5, 'text');
	add(`${c}-icon`, `${c}-bg`, 3, 'non-text');
}
add('text-disabled', ['bg-body', 'bg-surface'], null, 'text');

const level = (r) => (r >= 7 ? 'AAA' : r >= 4.5 ? 'AA' : r >= 3 ? 'AA large / non-text' : 'fail');
const failures = [];
const rows = [];
for (const [fg, bg, min, kind] of pairs) {
	const cells = ['light', 'dark'].map((mode) => {
		const r = ratio(tokens.color[fg][mode], tokens.color[bg][mode]);
		if (!Number.isFinite(r) || (min !== null && r < min)) failures.push(`${fg} on ${bg} (${mode}): ${r.toFixed(2)} < ${min}`);
		return `${r.toFixed(2)} ${level(r)}`;
	});
	rows.push(`| \`${fg}\` | \`${bg}\` | ${kind} | ${min === null ? 'none' : `${min}:1`} | ${cells[0]} | ${cells[1]} |`);
}

const contrastMd = `# Contrast report

Generated by \`scripts/build.mjs\` from \`tokens/cozy.tokens.json\`. Do not edit by hand.

The script uses the WCAG 2.x relative-luminance formula. It blends a translucent foreground over its background before it measures.

- **Minimum**: the build fails when a pair is below this value. "none" means the pair is for information only.
- **AAA**: 7:1 or more. **AA**: 4.5:1 or more. **AA large / non-text**: 3:1 or more.

| Foreground | Background | Kind | Minimum | Light | Dark |
| :--- | :--- | :--- | :--- | :--- | :--- |
${rows.join('\n')}
`;

// ---------- CSS ----------

const colorLines = Object.entries(tokens.color).map(([k, v]) => `\t${P}${k}: light-dark(${v.light}, ${v.dark});`);
const flat = (group, obj) => Object.entries(obj).map(([k, v]) => `\t${P}${group}-${k}: ${v};`);
const textLines = Object.entries(tokens.text).flatMap(([k, v]) => [
	`\t${P}text-${k}-size: ${v.size};`,
	`\t${P}text-${k}-leading: ${v.leading};`,
	`\t${P}text-${k}-weight: ${v.weight};`,
]);

const css = `/* Cozy design tokens ${tokens.version}. Generated from tokens/cozy.tokens.json. Do not edit by hand. */

:root {
	color-scheme: light dark;
}

:root[data-theme='light'] {
	color-scheme: light;
}

:root[data-theme='dark'] {
	color-scheme: dark;
}

:root {
${colorLines.join('\n')}

${flat('font', tokens.font).join('\n')}

${textLines.join('\n')}

${flat('space', tokens.space).join('\n')}

${flat('radius', tokens.radius).join('\n')}

${flat('shadow', tokens.shadow).join('\n')}

${flat('motion', tokens.motion).join('\n')}
}
`;

// ---------- TS ----------

const ts = `// Cozy design tokens ${tokens.version}. Generated from tokens/cozy.tokens.json. Do not edit by hand.

export const cozyTokens = ${JSON.stringify(tokens, null, '\t')} as const;

export type CozyColorToken = keyof typeof cozyTokens.color;
export type CozySpaceToken = keyof typeof cozyTokens.space;
export type CozyRadiusToken = keyof typeof cozyTokens.radius;
export type CozyShadowToken = keyof typeof cozyTokens.shadow;
export type CozyMotionToken = keyof typeof cozyTokens.motion;
export type CozyFontToken = keyof typeof cozyTokens.font;

type CozyGroupedVar =
	| \`space-\${CozySpaceToken}\`
	| \`radius-\${CozyRadiusToken}\`
	| \`shadow-\${CozyShadowToken}\`
	| \`motion-\${CozyMotionToken}\`
	| \`font-\${CozyFontToken}\`;

export type CozyVarToken = CozyColorToken | CozyGroupedVar;

/** Returns the CSS custom-property reference for a token, for example \`var(--cozy-accent)\` or \`var(--cozy-radius-element)\`. */
export function cozyVar(token: CozyVarToken): string {
	return \`var(${P}\${token})\`;
}
`;

// ---------- palette SVG ----------

const groups = ['surface', 'text', 'accent', 'status', 'line', 'nav', 'expressive', 'category'];
const SW = 76;
const GAP = 10;
const COLS = 8;
const ROW_H = 74;
const panelW = 24 * 2 + COLS * (SW + GAP) - GAP;
const svgFor = (mode) => {
	const theme = tokens.color;
	const bg = theme['bg-body'][mode];
	const fg = theme['text-primary'][mode];
	const muted = theme['text-secondary'][mode];
	let y = 56;
	const parts = [];
	for (const g of groups) {
		const entries = Object.entries(theme).filter(([, v]) => v.group === g);
		parts.push(`<text x="24" y="${y}" fill="${muted}" font-size="11" font-weight="600" letter-spacing="0.06em">${g.toUpperCase()}</text>`);
		y += 10;
		entries.forEach(([name, v], i) => {
			const cx = 24 + (i % COLS) * (SW + GAP);
			const cy = y + Math.floor(i / COLS) * ROW_H;
			parts.push(
				`<rect x="${cx}" y="${cy}" width="${SW}" height="40" rx="10" fill="${v[mode]}" stroke="${theme.border[mode]}"/>`,
				`<text x="${cx}" y="${cy + 54}" fill="${fg}" font-size="9.5">${name}</text>`,
				`<text x="${cx}" y="${cy + 66}" fill="${muted}" font-size="9" font-family="ui-monospace, monospace">${v[mode]}</text>`,
			);
		});
		y += Math.ceil(entries.length / COLS) * ROW_H + 22;
	}
	return `<svg xmlns="http://www.w3.org/2000/svg" width="${panelW}" height="${y}" viewBox="0 0 ${panelW} ${y}" font-family="'Plus Jakarta Sans', -apple-system, 'Segoe UI', sans-serif">
<rect x="0" y="0" width="${panelW}" height="${y}" fill="${bg}"/>
<text x="24" y="32" fill="${fg}" font-size="16" font-weight="700">Cozy · ${mode}</text>
${parts.join('\n')}
</svg>
`;
};

// ---------- preview page ----------

const pairedBg = new Map();
for (const [fg, bg] of pairs) {
	if (!pairedBg.has(fg)) pairedBg.set(fg, bg);
}
const swatchHtml = groups
	.map((g) => {
		const items = Object.entries(tokens.color)
			.filter(([, v]) => v.group === g)
			.map(([name, v]) => {
				const refBg = pairedBg.get(name) ?? (name === 'bg-body' ? null : 'bg-body');
				const contrast = refBg
					? `<small class="ratio">On ${refBg}: ${ratio(v.light, tokens.color[refBg].light).toFixed(2)} · ${ratio(v.dark, tokens.color[refBg].dark).toFixed(2)}</small>`
					: '';
				return `\t\t\t\t<li class="swatch"><button class="swatch-copy" type="button" data-copy="var(${P}${name})" aria-label="Copy var(${P}${name})"><span class="chip" style="background: var(${P}${name})"></span><code>${name}</code></button><small>${v.light} · ${v.dark}</small>${contrast}<small class="role">${v.role}</small></li>`;
			})
			.join('\n');
		return `\t\t\t<h3>${g}</h3>\n\t\t\t<ul class="swatches">\n${items}\n\t\t\t</ul>`;
	})
	.join('\n');
// GitHub Pages lets browsers cache files for 10 minutes. A content hash in each URL stops a new page from using an old file.
const hash = (text) => createHash('sha1').update(text).digest('hex').slice(0, 8);
const bgBodyLight = tokens.color['bg-body'].light;
const bgBodyDark = tokens.color['bg-body'].dark;
const textPrimaryLight = tokens.color['text-primary'].light;
const textPrimaryDark = tokens.color['text-primary'].dark;
const textAccentLight = tokens.color['text-accent'].light;
const textAccentDark = tokens.color['text-accent'].dark;

// CSS cannot run a spring. Sample COZY_SPRING over 360 ms (about its settle time) into linear() so CSS and JS move the same way.
const springLinear = (() => {
	const { stiffness, damping, mass } = COZY_SPRING;
	const dt = 1e-5;
	const steps = Math.round(0.36 / dt);
	const samples = [];
	let x = 0;
	let v = 0;
	for (let i = 0; i <= steps; i++) {
		samples.push(x);
		v += ((-stiffness * (x - 1) - damping * v) / mass) * dt;
		x += v * dt;
	}
	const points = Array.from({ length: 16 }, (_, i) => +samples[Math.round((i / 16) * steps)].toFixed(4));
	return `linear(${[...points, 1].join(', ')})`;
})();

const siteHtml = readFileSync(join(root, 'scripts/preview.template.html'), 'utf8')
	.replace('<!-- SWATCHES -->', swatchHtml.trimStart())
	.replaceAll('{{VERSION}}', tokens.version)
	.replaceAll('{{BG_BODY_LIGHT}}', bgBodyLight)
	.replaceAll('{{BG_BODY_DARK}}', bgBodyDark)
	.replaceAll('{{COZY_SPRING_LINEAR}}', springLinear)
	.replace('href="tokens/cozy.css"', `href="tokens/cozy.css?v=${hash(css)}"`)
	.replace('href="css/effects.css"', `href="css/effects.css?v=${hash(readFileSync(join(root, 'css/effects.css'), 'utf8'))}"`)
	.replace("'./js/cozy-motion.js'", `'./js/cozy-motion.js?v=${hash(readFileSync(join(root, 'js/cozy-motion.js'), 'utf8'))}'`);

// Legacy bookmark redirect for /cozy/preview/ -> /cozy/.
